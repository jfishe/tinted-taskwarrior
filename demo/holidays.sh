#!/bin/sh
# Write a Taskwarrior holiday rc (US holidays for this year and next) to $1,
# so the calendar's holiday color always has something to show.
# Easter is computed by Taskwarrior itself.
set -eu
out=${1:?usage: holidays.sh OUTPUT}

# nth_weekday YEAR MONTH WEEKDAY(1=Mon..7=Sun) N -> YYYYMMDD of the Nth one.
nth_weekday() {
  first=$(date -d "$1-$2-01" +%u)
  day=$((1 + ($3 - first + 7) % 7 + 7 * ($4 - 1)))
  printf '%04d%02d%02d' "$1" "$2" "$day"
}

year=$(date +%Y)
{
  echo "# Generated by demo/holidays.sh; do not edit."
  echo "holiday.easter.name=Easter Sunday"
  echo "holiday.easter.date=easter"
  for y in "$year" $((year + 1)); do
    echo "holiday.newyear$y.name=New Year's Day"
    echo "holiday.newyear$y.date=${y}0101"
    echo "holiday.mlk$y.name=Martin Luther King Jr. Day"
    echo "holiday.mlk$y.date=$(nth_weekday "$y" 1 1 3)"
    echo "holiday.memorial$y.name=Memorial Day"
    echo "holiday.memorial$y.date=$(date -d "$(nth_weekday "$y" 6 1 1) - 7 days" +%Y%m%d)"
    echo "holiday.independence$y.name=Independence Day"
    echo "holiday.independence$y.date=${y}0704"
    echo "holiday.labor$y.name=Labor Day"
    echo "holiday.labor$y.date=$(nth_weekday "$y" 9 1 1)"
    echo "holiday.veterans$y.name=Veterans Day"
    echo "holiday.veterans$y.date=${y}1111"
    echo "holiday.thanksgiving$y.name=Thanksgiving"
    echo "holiday.thanksgiving$y.date=$(nth_weekday "$y" 11 4 4)"
    echo "holiday.christmas$y.name=Christmas Day"
    echo "holiday.christmas$y.date=${y}1225"
  done
} > "$out"
